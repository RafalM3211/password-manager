    private void loginBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginBtnActionPerformed
       String login = loginInput.getText();
       String password = passwordInput.getText();
       
       PasswordLogin passwordLogin = new PasswordLogin(login, password);
       boolean isAuthSuccess = passwordLogin.authenticate();
       
       String resultText = isAuthSuccess? "Login successfull!": "Login failed";
       
       loginResult.setText(resultText);
       
       if(isAuthSuccess) {
           Home homeFrame = new Home();
           homeFrame.setVisible(true);
           this.dispose();
       }
    }//GEN-LAST:event_loginBtnActionPerformed


